import { assertStagedChangeIsSafe } from './commit-guard';
import { GitError, type GitRunner } from './git-runner';

export class CommitMessageError extends Error {
  constructor(message: string) {
    super(message);
    this.name = 'CommitMessageError';
  }
}

/** The push was rejected or failed. The ticket goes on hold (`needs_help`, BUILD_PLAN 6.8). */
export class PushRejectedError extends Error {
  constructor(
    message: string,
    readonly branch: string,
  ) {
    super(message);
    this.name = 'PushRejectedError';
  }
}

export interface GitIdentity {
  name: string;
  email: string;
}

/** Attribution that must never appear in a commit message (F9): trailers and "generated by" lines. */
const ATTRIBUTION: readonly [RegExp, string][] = [
  [/^\s*co-authored-by:/im, 'a Co-Authored-By trailer'],
  [/generated (with|by)\b/i, 'a "generated with/by" line'],
  [/🤖/u, 'a robot emoji attribution'],
  [/noreply@anthropic\.com/i, 'an Anthropic address'],
];

export function assertCommitMessage(message: string): void {
  if (message.trim() === '') throw new CommitMessageError('The commit message is empty');
  for (const [pattern, what] of ATTRIBUTION) {
    if (pattern.test(message)) throw new CommitMessageError(`The commit message contains ${what}; commits carry no AI attribution`);
  }
}

export type CommitResult = { committed: false } | { committed: true; sha: string };

/**
 * Stages everything and commits it as the configured identity (BUILD_PLAN 6.2). Repository hooks never run
 * (`core.hooksPath=/dev/null`) and the commit uses `--no-verify`. Returns `committed: false` when nothing changed.
 */
export async function commitAll(git: GitRunner, workspace: string, message: string, identity: GitIdentity, opts: { paths?: readonly string[] } = {}): Promise<CommitResult> {
  assertCommitMessage(message);
  if (!identity.name.trim() || !identity.email.trim()) throw new Error('GIT_AUTHOR_NAME and GIT_AUTHOR_EMAIL must be set to commit');

  // `paths` limits what is staged (the KB commit stages only the KB directory); the default stages everything.
  await git.run(['add', '-A', ...(opts.paths && opts.paths.length > 0 ? ['--', ...opts.paths] : [])], { cwd: workspace });
  if ((await git.out(['diff', '--cached', '--name-only'], { cwd: workspace })) === '') return { committed: false };
  await assertStagedChangeIsSafe(git, workspace); // node_modules, .env*, keys and files over 1 MB fail the stage

  await git.run(['commit', '--no-verify', '-m', message], {
    cwd: workspace,
    env: { GIT_AUTHOR_NAME: identity.name, GIT_AUTHOR_EMAIL: identity.email, GIT_COMMITTER_NAME: identity.name, GIT_COMMITTER_EMAIL: identity.email },
  });
  return { committed: true, sha: await git.out(['rev-parse', 'HEAD'], { cwd: workspace }) };
}

const PUSH_URL_PREFIX = 'https://github.com/';

/** What a push did besides pushing: the pipeline's own earlier commits it replaced on the remote (see `pushBranch`). */
export interface PushResult {
  replaced: string[];
  /** Every commit of the branch that the pipeline made (not on the base branch): record these, they are what a later rerun may replace. */
  pushed: string[];
}

/** Who may be replaced: only commits whose SHA the pipeline recorded when it pushed them. Author name and e-mail are not evidence (anyone can type them). */
export interface OwnCommits {
  knownShas: readonly string[];
  /** The base branch, so the commits to record are the ones on top of it. */
  baseBranch: string;
}

/** The lines of a failed push that say why, without the noise. */
const pushReason = (stderr: string): string =>
  stderr.split('\n').map((l) => l.trim()).filter((l) => /^(!|error:|hint:|fatal:|remote:)/i.test(l)).join(' ').slice(0, 600) || stderr.slice(0, 600);

/**
 * Pushes the ticket branch (https only, a github.com URL, hooks off). A normal push is tried first and never forced.
 *
 * One case is recovered by itself: the remote branch is not an ancestor of the local one (a rerun rebuilt the branch, so GitHub still holds
 * an earlier attempt of this same ticket) and every commit that only the remote has was made by the pipeline's own identity. Those commits
 * are superseded work, so the branch is pushed again with `--force-with-lease` pinned to the exact remote commit that was inspected: if
 * anyone pushed in the meantime, the lease fails and nothing is overwritten. A commit by anyone else is never replaced.
 *
 * `allowedUrlPrefixes` is only widened by tests.
 */
export async function pushBranch(git: GitRunner, workspace: string, branch: string, repoUrl: string, allowedUrlPrefixes: readonly string[] = [PUSH_URL_PREFIX], own?: OwnCommits): Promise<PushResult> {
  if (!branch || branch.startsWith('+') || branch.startsWith('-')) throw new Error(`Refusing to push "${branch}"`);
  if (!allowedUrlPrefixes.some((prefix) => repoUrl.startsWith(prefix))) throw new Error('Refusing to push: the repository URL is not a github.com URL');
  const refspec = `refs/heads/${branch}:refs/heads/${branch}`;
  try {
    await git.run(['push', repoUrl, refspec], { cwd: workspace });
    return { replaced: [], pushed: await ownCommitsOf(git, workspace, own) };
  } catch (err) {
    if (!(err instanceof GitError)) throw err;
    const nonFastForward = /non-fast-forward|tip of your current branch is behind|fetch first/i.test(err.stderr);
    if (!own || !nonFastForward) throw new PushRejectedError(`Push of ${branch} was rejected: ${pushReason(err.stderr)}`, branch);
    return replaceOwnCommits(git, workspace, branch, repoUrl, refspec, own, err);
  }
}

/** The commits on the branch that are not on the base branch (what the pipeline made), or [] when that cannot be worked out. */
async function ownCommitsOf(git: GitRunner, workspace: string, own: OwnCommits | undefined): Promise<string[]> {
  if (!own) return [];
  try {
    const out = await git.out(['rev-list', '--max-count=2000', 'HEAD', '--not', `refs/remotes/origin/${own.baseBranch}`], { cwd: workspace });
    return out.split('\n').filter(Boolean);
  } catch {
    return [];
  }
}

async function replaceOwnCommits(git: GitRunner, workspace: string, branch: string, repoUrl: string, refspec: string, own: OwnCommits, rejected: GitError): Promise<PushResult> {
  const fail = (why: string) => new PushRejectedError(`Push of ${branch} was rejected: ${why}`, branch);
  try {
    await git.run(['fetch', repoUrl, `refs/heads/${branch}`], { cwd: workspace });
    const remoteSha = (await git.run(['rev-parse', 'FETCH_HEAD'], { cwd: workspace })).stdout.trim();
    const onlyRemote = (await git.run(['log', '--format=%H', remoteSha, '--not', 'HEAD'], { cwd: workspace })).stdout.split('\n').filter(Boolean).map((l) => [l]);
    if (onlyRemote.length === 0) throw fail(pushReason(rejected.stderr));
    const known = new Set(own.knownShas);
    const foreign = onlyRemote.filter(([sha]) => !known.has(sha ?? ''));
    if (foreign.length > 0) throw fail(`the remote branch has commits the pipeline did not push (${foreign.map(([sha]) => (sha ?? '').slice(0, 8)).join(', ')}), so they were not replaced`);
    await git.run(['push', `--force-with-lease=refs/heads/${branch}:${remoteSha}`, repoUrl, refspec], { cwd: workspace });
    return { replaced: onlyRemote.map(([sha]) => sha ?? ''), pushed: await ownCommitsOf(git, workspace, own) };
  } catch (err) {
    if (err instanceof PushRejectedError) throw err;
    if (err instanceof GitError) throw fail(`${pushReason(err.stderr)} (the remote branch changed while it was being replaced, or could not be read)`);
    throw err;
  }
}
